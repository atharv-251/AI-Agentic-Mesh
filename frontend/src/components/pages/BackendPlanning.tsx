import { useEffect, useRef, useState } from 'react';
import { request } from '../../api/client';
import { isRecord, parseOutput } from './amplifyPresentation';
import { StructuredOutput } from './StructuredOutput';

interface BackendPlan {
  id: string;
  status: string;
  proposal: Record<string, unknown>;
  result: {
    release_status: string;
    scheduled_hours: number;
    sessions: { id: string; title: string; date: string; start: string; hours: number; sme_name: string; receiver_name: string }[];
    blockers: string[];
  } | null;
  error: string | null;
  delivery_status: string;
  delivery_recipients: string[] | null;
  delivery_error: string | null;
  report_sha256: string | null;
  origin: { type: 'amplify' | 'historical_backend_only'; run_id: string | null; transfer: string | null };
}

export function BackendPlanning({ transitionId, amplifyRunId }: { transitionId: string; amplifyRunId: string | null }) {
  const [plan, setPlan] = useState<BackendPlan | null>(null);
  const [proposal, setProposal] = useState('');
  const [name, setName] = useState('');
  const [approval, setApproval] = useState(false);
  const [emailApproval, setEmailApproval] = useState(false);
  const [recipients, setRecipients] = useState('');
  const [busy, setBusy] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const mounted = useRef(true);
  const requestId = useRef(crypto.randomUUID());
  const historical = plan?.origin.type === 'historical_backend_only';
  const reviewedOutput = parseOutput(proposal);
  const reviewedRecord = reviewedOutput.kind === 'json' && isRecord(reviewedOutput.value) ? reviewedOutput.value : null;
  const categories = ['unclassified', 'functional', 'business', 'support_process', 'technical', 'development', 'database', 'ams_operations', 'integration'];
  const base = `/transitions/${encodeURIComponent(transitionId)}/backend-plan`;
  const accept = (saved: BackendPlan | null) => {
    setPlan(saved);
    if (saved) setProposal(JSON.stringify(saved.proposal, null, 2));
  };
  useEffect(() => {
    mounted.current = true;
    const controller = new AbortController();
    request<BackendPlan | null>(base, { signal: controller.signal }).then(saved => {
      if (!controller.signal.aborted) accept(saved);
    }).catch((err: unknown) => {
      if (!controller.signal.aborted) {
        console.error('Backend plan loading failed', err);
        setError(err instanceof Error ? err.message : 'Could not load backend plan');
      }
    }).finally(() => { if (!controller.signal.aborted) setBusy(false); });
    return () => { mounted.current = false; controller.abort(); };
  }, [base]);
  const perform = async (action: () => Promise<BackendPlan>) => {
    setBusy(true);
    setError(null);
    try {
      const saved = await action();
      if (mounted.current) accept(saved);
    } catch (err) {
      console.error('Backend planning action failed', err);
      if (mounted.current) setError(err instanceof Error ? err.message : 'Planning action failed');
    } finally {
      if (mounted.current) setBusy(false);
    }
  };
  const inputClass = 'mt-2 block w-full rounded-lg border border-slate-600 bg-slate-950 p-3 text-sm';
  return <section className="mission-panel space-y-5" aria-label="Amplify operational review">
    <div><p className="mission-eyebrow">05 Review agent inputs / 06 Validate &amp; save / 07 Approved delivery</p>
      <h2 className="mt-2 text-2xl font-semibold">{historical ? 'Historical backend-only test' : 'Put Amplify outputs into operation'}</h2>
      <p className="mt-3 text-sm text-slate-300">Amplify is mandatory. This backend only adapts completed agent outputs for your review, runs deterministic calculations, saves SQL records and creates the professional report. It does not call a local planning model.</p>
      <p className="mission-notice mt-4">{historical ? 'Read-only historical record: this earlier test was NOT generated by Amplify. Its report and delivery receipt are preserved. It cannot be rerun, relabelled or sent again through this interface. Use a new transition for the mandatory Amplify flow.' : 'Requires an accepted submission for this KT and all seven completed agent outputs. Result transfer is currently a manual, unverified snapshot. Review classifications, KT levels and any scheduling differences before saving. No invitations or readiness are inferred.'}</p>
    </div>
    {busy && <p role="status">Working. Keep this page open; refresh saved state after a connection interruption.</p>}
    {error && <p role="alert" className="break-words text-red-300">{error}</p>}
    <button type="button" disabled={busy} className="text-sm text-cyan-200 underline" onClick={() => void perform(async () => {
      const saved = await request<BackendPlan | null>(base);
      if (!saved) throw new Error('No operational review yet. Complete Amplify and import its result first.');
      return saved;
    })}>Refresh saved review</button>
    {!plan && <form className="space-y-4" onSubmit={event => {
      event.preventDefault();
      if (!amplifyRunId) return;
      const form = new FormData();
      form.append('request_id', requestId.current);
      form.append('amplify_run_id', amplifyRunId);
      void perform(() => request<BackendPlan>(base, { method: 'POST', body: form }));
    }}>
      <p className="break-all text-sm">{amplifyRunId ? `Selected Amplify run: ${amplifyRunId}` : 'Locked: complete Amplify, import the Full JSON, then choose its result snapshot above.'}</p>
      <button className="mission-button" disabled={busy || !amplifyRunId}>Prepare review from Amplify outputs</button>
    </form>}
    {plan && <div className="space-y-4">
      <p className="break-all text-sm">{historical ? 'Historical execution' : 'Operational calculation'}: <strong>{plan.status}</strong> / {plan.id}{plan.result && ' / KT delivery remains draft'}</p>
      {plan.origin.run_id && <p className="break-all text-xs text-cyan-200">Immutable source run: {plan.origin.run_id} / manual snapshot</p>}
      {plan.error && <p role="alert" className="text-red-300">{plan.error}</p>}
      {!historical && plan.status !== 'completed' && <form className="space-y-4" onSubmit={event => {
        event.preventDefault();
        void perform(async () => request<BackendPlan>(`${base}/execute`, {
          method: 'POST', body: JSON.stringify({ proposal: JSON.parse(proposal), reviewed_by: name, approve_operational_write: true }),
        }));
      }}>
        <p className="text-sm text-amber-200">Verify names, KT levels, effort estimates, evidence and assumptions against the original agent outputs. Replace every "unclassified" topic category with one of: functional, business, support_process, technical, development, database, ams_operations, integration. These classifications are never guessed. Workspace dates and capacity settings remain authoritative. Existing operational records are never overwritten.</p>
        {reviewedRecord && <section className="review-input-preview" aria-label="Reviewable operational inputs"><h3 className="mb-4 text-lg font-semibold">Reviewable operational inputs</h3><StructuredOutput value={reviewedRecord} /></section>}
        {reviewedRecord && Array.isArray(reviewedRecord.topics) && <fieldset className="review-classifications"><legend>Operational topic classifications</legend><p>Choose an exact classification for each topic. Changing a category resets your approval.</p>{reviewedRecord.topics.map((topic, index) => isRecord(topic) && typeof topic.name === 'string' && typeof topic.category === 'string' ? <label key={index}>{topic.name}<select disabled={busy} value={topic.category} onChange={event => {
          if (!Array.isArray(reviewedRecord.topics)) return;
          const topics = reviewedRecord.topics.map((item, itemIndex) => itemIndex === index && isRecord(item) ? { ...item, category: event.target.value } : item);
          setProposal(JSON.stringify({ ...reviewedRecord, topics }, null, 2));
          setApproval(false);
        }}>{categories.map(category => <option key={category} value={category}>{category.replace(/_/g, ' ')}</option>)}</select></label> : null)}</fieldset>}
        {reviewedOutput.kind === 'invalid' && <p className="mission-notice" role="alert">{reviewedOutput.message} Correct the advanced inputs before saving.</p>}
        <details className="raw-output"><summary>Advanced: edit operational inputs</summary><p>For corrections to people, KT levels, effort or other fields. These reviewed inputs stay separate from the immutable original Amplify response. The backend validates all fields before execution.</p><label className="mt-4 block text-sm">Reviewable proposal JSON<textarea rows={14} disabled={busy} value={proposal} onChange={e => { setProposal(e.target.value); setApproval(false); }} className={`${inputClass} font-mono text-xs`} /></label></details>
        <label className="block text-sm">Reviewer name<input required maxLength={100} value={name} onChange={e => setName(e.target.value)} className={inputClass} /></label>
        <label className="flex items-start gap-3 text-sm"><input type="checkbox" required checked={approval} onChange={e => setApproval(e.target.checked)} /> I reviewed these inputs and approve saving operational profile, people, hierarchy, levels and schedule. This is not release approval.</label>
        <button className="mission-button" disabled={busy || !approval || !name.trim() || reviewedOutput.kind !== 'json' || ['preparing', 'running'].includes(plan.status)}>Validate &amp; save reviewed Amplify plan</button>
      </form>}
      {plan.result && <>
        <p className="text-cyan-200">{plan.result.sessions.length} saved sessions / {plan.result.scheduled_hours} scheduled hours / {plan.result.release_status}</p>
        <div className="space-y-2">{plan.result.sessions.map(session => <article key={session.id} className="rounded-lg border border-slate-700 p-3 text-sm">
          <strong>{session.title}</strong><p>{session.date} {session.start} / {session.hours}h</p><p>{session.sme_name} → {session.receiver_name}</p>
        </article>)}</div>
        <details><summary className="cursor-pointer text-amber-200">Outstanding review actions ({plan.result.blockers.length})</summary><ul className="mt-3 list-inside list-disc space-y-2 text-sm">{plan.result.blockers.map((blocker, i) => <li key={i}>{blocker}</li>)}</ul></details>
        <div className="flex flex-wrap gap-4">
          <a className="mission-button" href={`/api/v1${base}/report`}>Download complete Word report</a>
        </div>
        <details className="rounded-lg border border-slate-700 p-4">
          <summary className="cursor-pointer text-cyan-200">{historical ? 'Historical delivery receipt' : 'Approve report email'}</summary>
          <p className="mt-3 text-sm">Delivery state: {plan.delivery_status}. SMTP acceptance is not proof of inbox delivery. No automatic resend after an attempted send.</p>
          {plan.delivery_recipients && <p className="mt-2 break-words text-sm">Recipients: {plan.delivery_recipients.join(', ')}</p>}
          {plan.delivery_error && <p className="mt-2 break-words text-sm text-amber-200">{plan.delivery_error}</p>}
          {!historical && <form className="mt-4 space-y-4" onSubmit={event => {
            event.preventDefault();
            void perform(() => request<BackendPlan>(`${base}/email`, { method: 'POST', body: JSON.stringify({
              recipients: recipients.split(/[,;\n]+/).map(s => s.trim()).filter(Boolean),
              approved_by: name, approve_email: true,
            }) }));
          }}>
            <label className="block text-sm">Recipients, separated by commas<textarea required value={recipients} onChange={e => { setRecipients(e.target.value); setEmailApproval(false); }} className={inputClass} /></label>
            <label className="block text-sm">Email approved by<input required maxLength={100} value={name} onChange={e => setName(e.target.value)} className={inputClass} /></label>
            <label className="flex items-start gap-3 text-sm"><input type="checkbox" required checked={emailApproval} onChange={e => setEmailApproval(e.target.checked)} /> I approve sending this exact draft Word report and its documented blockers to these recipients.</label>
            <button className="mission-button" disabled={busy || !emailApproval || !name.trim() || plan.delivery_status !== 'not_sent'}>Send approved report attachment</button>
          </form>}
        </details>
      </>}
    </div>}
  </section>;
}
